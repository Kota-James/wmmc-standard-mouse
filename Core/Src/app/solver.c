/*
 * solver.c — 経路探索（足立法）の実装
 */

#include "app/solver.h"

uint8_t smap[MAZE_SIZE][MAZE_SIZE];
uint8_t route[256];
uint8_t r_cnt;

#define STEP_UNREACHED 0xff // 歩数マップの「未記入」印

void solver_init(void) { r_cnt = 0; }

//+++++++++++++++++++++++++++++++++++++++++++++++
// solver_make_step_map
// 歩数マップを作成する
// ゴールを歩数0とし，壁がない隣の区画に歩数+1を書き込む作業を
// 自分の座標に歩数が書かれるまで繰り返す
//+++++++++++++++++++++++++++++++++++++++++++++++
void solver_make_step_map(void) {
    uint8_t x, y;

    //----歩数マップのクリア----
    for (y = 0; y < MAZE_SIZE; y++) {
        for (x = 0; x < MAZE_SIZE; x++) {
            smap[y][x] = STEP_UNREACHED;
        }
    }

    //----ゴール座標を歩数0にする----
    smap[goal_y][goal_x] = 0;

    // ================= 課題4-1 =================
    // TODO: ゴール(歩数0)から歩数を広げていき，
    //       自分の座標 smap[mouse.y][mouse.x] に歩数が書かれるまで繰り返す
    //
    // 素直な実装（まずはこれでよい）:
    //   「マップ全域を走査して歩数nの区画を見つけ，壁のない未記入の隣に n+1 を書く」
    //   を n=0,1,2,... と繰り返す
    //
    // 使うもの:
    //   maze_wall_bits(x, y) … その区画の壁4bit（bit3=北 bit2=東 bit1=南 bit0=西。
    //                          一次/二次走行のニブル選択は自動で行われる）
    //   STEP_UNREACHED       … 未記入の印(0xff)
    //
    // 注意:
    //   - 端の区画で配列の外に書かないこと
    //   - ゴールが到達不能なマップを渡されても無限ループしないこと
    //     （歩数が0xffに達したら打ち切る，など）
    //
    // 発展: この方式は遅い。キューを使った幅優先探索に書き換えると数十倍速くなる
    // 詳細: docs/exercises/04_足立法.md
    // ==========================================
    (void)x;
    (void)y; // 実装したらこの2行は消す（未使用警告よけ）
}

//+++++++++++++++++++++++++++++++++++++++++++++++
// solver_make_route
// 歩数マップを歩数が減る方向へたどり，最短経路route[]を導出する
//+++++++++++++++++++++++++++++++++++++++++++++++
void solver_make_route(void) {
    uint8_t x, y;
    uint8_t dir_temp = mouse.dir; // 探索中に内部方角を使うので退避する
    uint16_t i;

    //----最短経路を初期化----
    for (i = 0; i < 256; i++) {
        route[i] = 0xff;
    }

    //----現在座標から出発----
    x = mouse.x;
    y = mouse.y;

    // ================= 課題4-2 =================
    // TODO: 現在座標(x,y)から歩数マップの値が減る方向へたどり，
    //       ゴール（歩数0）に着くまでの動作列を route[] に書き込む
    //
    // 手順のヒント:
    //   1. 壁がなく歩数が今より小さい隣の区画を探す（maze_wall_bits, smap）
    //   2. 「北に進みたい」を「今の向きから見て右折」のような相対方向に変換する。
    //      相対方向 = (絶対方位 - mouse.dir) & 0x03
    //   3. 相対方向を動作形式に変換して route[i] に格納する:
    //      0(前進)→0x88, 1(右折)→0x44, 2(Uターン)→0x22, 3(左折)→0x11
    //      旋回のときは maze_turn() で内部方角も回しながら組み立てる
    //      （mouse.dirは上でdir_tempに退避済み。最後に復元される）
    //   4. i が route[] の容量(256)を超えないように打ち切ること
    //
    // 詳細: docs/exercises/04_足立法.md
    // ==========================================
    (void)x;
    (void)y;
    (void)i; // 実装したらこの3行は消す（未使用警告よけ）

    mouse.dir = dir_temp; // 退避した内部方角を復元する
}

//+++++++++++++++++++++++++++++++++++++++++++++++
// solver_update_route
// 壁情報をマップに書き込み，次の進路が壁で塞がれていれば経路を作り直す
//+++++++++++++++++++++++++++++++++++++++++++++++
void solver_update_route(uint8_t wall_info) {
    //----壁情報書き込み----
    maze_write_walls(wall_info);

    //----最短経路上に壁があれば進路変更----
    if (wall_info & route[r_cnt]) {
        solver_make_step_map();
        solver_make_route();
        r_cnt = 0;
    }
}
