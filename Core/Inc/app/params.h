#ifndef APP_PARAMS_H_
#define APP_PARAMS_H_

/*------------------------------------------------------------
    走行系
------------------------------------------------------------*/
//----走行パルス関連----
// 迷路の1区画は180mm（クラシック競技）。半区画=90mm進むのに必要なモータのパルス数
#define PULSE_SEC_HALF 218    // 半区画走行用パルス。2倍すると1区画分に
#define PULSE_ROT_R90 159     // 右90度回転用パルス数
#define PULSE_ROT_L90 159     // 左90度回転用パルス数
#define PULSE_ROT_180 316     // 180度回転用パルス数
#define PULSE_SETPOS_BACK 300 // 尻当てで後ろ壁に当てるために下がるパルス数
#define PULSE_SETPOS_SET 94   // 後ろ壁から区画中央までのパルス数

//----速度関連----
#define MAX_T_CNT PULSE_SEC_HALF // 加減速テーブルをどこまで進むか（＝最高速度）
                                 // 半区画で加速しきれる範囲に収めている
#define DEFAULT_INTERVAL 3000    // 旋回時のパルス間隔[µs]（小さいほど速く回る）

/*------------------------------------------------------------
    センサ系
------------------------------------------------------------*/
//----壁判断閾値（しきい値）----
// センサ値がこれより大きければ「壁あり」と判断する
#define WALL_BASE_FR 200 // 前壁右センサ
#define WALL_BASE_FL 200 // 前壁左センサ
#define WALL_BASE_R 200  // 右壁センサ
#define WALL_BASE_L 200  // 左壁センサ

//----壁制御----
#define CTRL_BASE_L 100 // 左制御閾値（この偏差までは制御しない＝不感帯）
#define CTRL_BASE_R 100 // 右制御閾値
#define CTRL_MAX 350    // 制御量上限値
#define CTRL_CONT 0.3F  // 比例制御係数（ゲイン）

/*------------------------------------------------------------
    探索系
------------------------------------------------------------*/
//----ゴール座標----
#define GOAL_X 7
#define GOAL_Y 7

/*------------------------------------------------------------
    安全装置
------------------------------------------------------------*/
// 走行開始前にバッテリ低電圧なら走行を拒否する（脱調・LiPo過放電の防止）。
// 大会でどうしても走らせたい場合は 0 にすると無効化できる。
// ただし電圧不足のまま走ると途中で脱調して完走できない可能性が高いことは理解しておくこと
#define BATT_CHECK_ENABLED 1

/*------------------------------------------------------------
    ここにない定数について
------------------------------------------------------------*/
// バッテリ低電圧閾値（分圧抵抗で決まる）や赤外線LEDの発光待ち時間など，
// 機体の配線・回路に固有で「調整」の対象でないものは platform 側にある
// （Core/Src/platform/hw_sensor.c 等を参照）

#endif /* APP_PARAMS_H_ */
